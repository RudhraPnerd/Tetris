class Piece:
    def __init__(self, kind):
        self.kind = kind
        self.x = 3
        self.y = 0
        self.rotation = 0

    def cells(self):
        offsets = SHAPES[self.kind][self.rotation]
        return [(self.x + ox, self.y + oy) for ox, oy in offsets]